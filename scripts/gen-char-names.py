#!/usr/bin/env python3
"""Writes src/tools/chars/names.ts: the official Unicode name of every
character Specialtecken can show, from Python's unicodedata. Run it after
adding a character to src/tools/chars/data.ts:

    python3 scripts/gen-char-names.py

A unit test fails while a character has no name."""
import json
import subprocess
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src/tools/chars/names.ts"

LIST = "import('./src/tools/chars/data.ts').then((m) => console.log(JSON.stringify(m.allGlyphs())))"
chars = json.loads(subprocess.check_output(["node", "--no-warnings", "-e", LIST], cwd=ROOT))

lines = [
    "// Generated by scripts/gen-char-names.py from Unicode "
    f"{unicodedata.unidata_version}. Don't edit; rerun the script.",
    "// Code point (hex) -> official name.",
    "export const UNICODE_NAMES: Record<string, string> = {",
]
for code in sorted(ord(c) for c in chars):
    lines.append(f'  "{code:04X}": "{unicodedata.name(chr(code))}",')
lines.append("};")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{len(chars)} names -> {OUT.relative_to(ROOT)}")
